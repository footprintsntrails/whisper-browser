//! Turns rules.toml into Rust tables (OUT_DIR/rules_gen.rs) that src/rules.rs includes.
//! A mistake in the rules stops the build with a message naming the rule; whether every
//! pattern compiles is checked by the tests (regex is not a build dependency).

use std::collections::HashSet;
use std::fmt::Write as _;
use std::path::Path;

const CLASSES: &[(&str, &str)] = &[
    ("chain", "Class::Chain"),
    ("aggravator", "Class::Aggravator"),
    ("lure", "Class::Lure"),
    ("padding", "Class::Padding"),
    ("tool", "Class::Tool"),
];

const REASONS: &[(&str, &str)] = &[
    ("download_run", "Reason::DownloadRun"),
    ("decode_run", "Reason::DecodeRun"),
    ("remote_tool", "Reason::RemoteTool"),
    ("unc_run", "Reason::UncRun"),
    ("hidden_window", "Reason::HiddenWindow"),
    ("obfuscated", "Reason::Obfuscated"),
    ("raw_ip", "Reason::RawIp"),
    ("lure_comment", "Reason::LureComment"),
    ("padded_comment", "Reason::PaddedComment"),
    ("quarantine_removal", "Reason::QuarantineRemoval"),
    ("abused_tool", "Reason::AbusedTool"),
];

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let rules_path = Path::new(&manifest).join("rules.toml");
    println!("cargo:rerun-if-changed={}", rules_path.display());
    println!("cargo:rerun-if-changed=build.rs");

    let text = std::fs::read_to_string(&rules_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", rules_path.display()));
    let table: toml::Table = text
        .parse()
        .unwrap_or_else(|e| panic!("rules.toml is not valid TOML: {e}"));

    let out = generate(&table).unwrap_or_else(|e| panic!("rules.toml: {e}"));
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let dest = Path::new(&out_dir).join("rules_gen.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", dest.display()));
}

fn generate(table: &toml::Table) -> Result<String, String> {
    let mut out = String::from("// Generated by build.rs from rules.toml. Do not edit.\n\n");

    let format = table
        .get("format")
        .and_then(toml::Value::as_integer)
        .ok_or("`format` is missing")?;
    if format != 1 {
        return Err(format!("format {format} is not supported (expected 1)"));
    }

    let placeholder = string(table, "placeholder")?;
    // One line, nothing a shell, the Run box or Explorer's address bar would act on.
    if !placeholder.starts_with("# ")
        || !placeholder
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == ' ' || c == '#')
    {
        return Err(
            "`placeholder` must start with \"# \" and hold only letters, digits and spaces".into(),
        );
    }
    writeln!(out, "pub(crate) const PLACEHOLDER: &str = {placeholder:?};").unwrap();

    let max_scan = table
        .get("max_scan_bytes")
        .and_then(toml::Value::as_integer)
        .ok_or("`max_scan_bytes` is missing")?;
    if !(4096..=16 * 1024 * 1024).contains(&max_scan) {
        return Err("`max_scan_bytes` must be between 4096 and 16777216".into());
    }
    writeln!(out, "pub(crate) const MAX_SCAN_BYTES: usize = {max_scan};").unwrap();

    let command = table
        .get("command")
        .and_then(toml::Value::as_table)
        .ok_or("[command] is missing")?;
    let words = strings(command, "words", "[command]")?;
    for w in &words {
        if w.is_empty() || w != &w.to_ascii_lowercase() || !w.is_ascii() {
            return Err(format!("command word {w:?} must be lower-case ASCII"));
        }
    }
    writeln!(out, "pub(crate) const COMMAND_WORDS: &[&str] = &{words:?};").unwrap();

    let features = table
        .get("feature")
        .and_then(toml::Value::as_array)
        .ok_or("no [[feature]] entries")?;
    let mut ids = HashSet::new();
    out.push_str("pub(crate) const FEATURES: &[FeatureDef] = &[\n");
    for (i, f) in features.iter().enumerate() {
        let f = f.as_table().ok_or(format!("feature #{i} is not a table"))?;
        let id = string(f, "id")?;
        let ctx = format!("feature {id:?}");
        if !ids.insert(id.clone()) {
            return Err(format!("{ctx} is defined twice"));
        }
        let class = lookup(CLASSES, &string(f, "class")?, &ctx, "class")?;
        let reason = lookup(REASONS, &string(f, "reason")?, &ctx, "reason")?;
        let strong = boolean(f, "strong")?;
        let low_alone = boolean(f, "low_alone")?;
        let anchors = strings(f, "anchors", &ctx)?;
        if anchors.is_empty() {
            return Err(format!("{ctx} has no anchors"));
        }
        for a in &anchors {
            if a.is_empty() || !a.is_ascii() || a != &a.to_ascii_lowercase() {
                return Err(format!(
                    "{ctx}: anchor {a:?} must be non-empty lower-case ASCII"
                ));
            }
        }
        let pattern = join_pattern(&string(f, "pattern")?);
        if pattern.is_empty() {
            return Err(format!("{ctx} has an empty pattern"));
        }
        if !pattern.is_ascii() {
            return Err(format!("{ctx}: the pattern must be ASCII"));
        }
        writeln!(
            out,
            "    FeatureDef {{ id: {id:?}, class: {class}, reason: {reason}, strong: {strong}, \
             low_alone: {low_alone}, anchors: &{anchors:?}, pattern: {pattern:?} }},"
        )
        .unwrap();
    }
    out.push_str("];\n\n");

    let installers = table
        .get("installer")
        .and_then(toml::Value::as_array)
        .ok_or("no [[installer]] entries")?;
    out.push_str("pub(crate) const INSTALLERS: &[InstallerDef] = &[\n");
    for (i, inst) in installers.iter().enumerate() {
        let inst = inst
            .as_table()
            .ok_or(format!("installer #{i} is not a table"))?;
        let name = string(inst, "name")?;
        let ctx = format!("installer {name:?}");
        let prefixes = strings(inst, "prefixes", &ctx)?;
        if prefixes.is_empty() {
            return Err(format!("{ctx} has no prefixes"));
        }
        for p in &prefixes {
            let host = p.split('/').next().unwrap_or_default();
            if p.contains("://")
                || p != &p.to_ascii_lowercase()
                || !host.contains('.')
                || host.starts_with('.')
                || host.ends_with('.')
            {
                return Err(format!(
                    "{ctx}: prefix {p:?} must be a lower-case host (and path) without scheme"
                ));
            }
            if host == "raw.githubusercontent.com" && p.matches('/').count() < 3 {
                return Err(format!(
                    "{ctx}: {p:?} must name an owner and a repository on raw.githubusercontent.com"
                ));
            }
        }
        writeln!(
            out,
            "    InstallerDef {{ name: {name:?}, prefixes: &{prefixes:?} }},"
        )
        .unwrap();
    }
    out.push_str("];\n");
    Ok(out)
}

/// A pattern written over several lines: each line trimmed, then joined.
fn join_pattern(raw: &str) -> String {
    raw.lines().map(str::trim).collect::<String>()
}

fn string(t: &toml::Table, key: &str) -> Result<String, String> {
    t.get(key)
        .and_then(toml::Value::as_str)
        .map(str::to_owned)
        .ok_or(format!("`{key}` is missing or not a string"))
}

fn boolean(t: &toml::Table, key: &str) -> Result<bool, String> {
    match t.get(key) {
        None => Ok(false),
        Some(v) => v.as_bool().ok_or(format!("`{key}` must be true or false")),
    }
}

fn strings(t: &toml::Table, key: &str, ctx: &str) -> Result<Vec<String>, String> {
    t.get(key)
        .and_then(toml::Value::as_array)
        .ok_or(format!("{ctx}: `{key}` is missing or not a list"))?
        .iter()
        .map(|v| {
            v.as_str()
                .map(str::to_owned)
                .ok_or(format!("{ctx}: `{key}` must hold strings"))
        })
        .collect()
}

fn lookup(
    table: &[(&str, &'static str)],
    key: &str,
    ctx: &str,
    what: &str,
) -> Result<&'static str, String> {
    table
        .iter()
        .find(|(k, _)| *k == key)
        .map(|(_, v)| *v)
        .ok_or(format!("{ctx}: unknown {what} {key:?}"))
}
