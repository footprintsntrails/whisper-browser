#!/usr/bin/env python3
"""Writes SeedWordlists.sys.mjs from the ten official BIP39 word lists.

Usage: gen-bip39-wordlists.py DIR
DIR holds english.txt, japanese.txt, ... as published in
https://github.com/bitcoin/bips/tree/master/bip-0039 (MIT License). Each file must have
2048 lines; the SHA-256 of each file goes into the module next to its words, and
detectors.test.mjs checks that the words joined back give exactly that file.
"""

import hashlib
import os
import sys

LANGS = [("english", "English"), ("spanish", "Spanish"), ("french", "French"),
         ("italian", "Italian"), ("portuguese", "Portuguese"), ("czech", "Czech"),
         ("japanese", "Japanese"), ("korean", "Korean"),
         ("chinese_simplified", "Chinese (Simplified)"),
         ("chinese_traditional", "Chinese (Traditional)")]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "overlay", "browser",
                   "components", "whisper", "security", "SeedWordlists.sys.mjs")

HEADER = """/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

// The ten official BIP39 word lists, unchanged, one string per language with the
// 2048 words in order, separated by single spaces.
//
// Source: https://github.com/bitcoin/bips/tree/master/bip-0039 ("This BIP falls under
// the MIT License", BIP 39 header). The SHA-256 of each original file (the words one
// per line, each followed by "\\n") is listed with it; gecko/tests/security checks
// that joining the words back gives exactly that file.
//
// Generated by gecko/tests/security/gen-bip39-wordlists.py. Loaded only when a
// field holds text that could be a phrase (SeedPhrase.sys.mjs), never at startup.

export const WORDLISTS = {"""


def main():
    src = sys.argv[1]
    out = [HEADER]
    for code, name in LANGS:
        data = open(os.path.join(src, f"{code}.txt"), "rb").read()
        words = data.decode("utf-8").split("\n")
        if words[-1] != "" or len(words) != 2049:
            raise SystemExit(f"{code}.txt: expected 2048 lines ending in a newline")
        words = words[:-1]
        digest = hashlib.sha256(data).hexdigest()
        out.append(f"  // {name}, {code}.txt, SHA-256 {digest}")
        out.append(f'  {code}: {{ sha256: "{digest}", words: "{" ".join(words)}" }},')
    out.append("};")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
